#pragma once

#include <string>
#include <vector>
#include <cstdint>

namespace history
{

struct Item
{
    std::string id;          // unique id, generated by makeId()
    std::string source;      // file path, torrent file path, magnet URI, or stream URL
    int fileIndex = -1;      // file index in torrent (-1 for single file / local file)
    std::string title;       // display title
    std::string sourceType;  // "Local", "Torrent", "Jackett", "Stremio"
    std::string posterPath;  // artwork / poster path
    double positionSec = 0.0;
    double durationSec = 0.0;
    int64_t lastWatched = 0; // unix timestamp (seconds)
    bool completed = false;

    // Stremio-specific metadata (for Stremio resume/sync)
    std::string stremioAuthKey;
    std::string stremioItemId;
    std::string stremioVideoId;
    std::string stremioType;
};

// Generates a canonical ID for history lookup and persistence
std::string makeId(const std::string& source, int fileIndex, const std::string& stremioVideoId = "");

// Reads history from disk (APPDATA_HISTORY)
void load();

// Writes history to disk
void save();

// Returns all history items, sorted newest to oldest (max 100)
std::vector<Item> all();

// Finds an item by source, fileIndex, and optional stremioVideoId, copying it
// into `out`. A copy, not a pointer: the list is shared with the player, which
// records into it while the UI reads, and a record() reallocates it.
bool find(const std::string& source, int fileIndex, const std::string& stremioVideoId,
          Item& out);

// Adds or updates an item in history, re-sorts and limits to 100 items, and
// saves. `saveNow` writes the file before returning; the player's periodic
// update passes false so the SD write runs off the UI thread instead of
// stalling a frame every 15 seconds.
void record(const Item& item, bool saveNow = true);

// Removes a single item by id
void remove(const std::string& id);

// Clears all history
void clear();

// Incremented on every change (record, remove, clear) to detect stale UI views
uint32_t generation();

// Checks if the item has a valid resume point (not completed, >= 15s and < 95% of duration)
bool hasValidResume(const Item& item);

} // namespace history
